def _fill(text: str, names: dict, ctx: dict) -> str:
    vals = {**ctx, **names}

    def rep(m: re.Match) -> str:
        return str(vals.get(m.group(1), m.group(0)))

    return re.sub(r"\{(\w+)\}", rep, text)


def fp(text: str) -> str:
    t = re.sub(r"@\S+", "@", (text or "").lower())
    t = re.sub(r"\s+", " ", t).strip()
    return hashlib.sha1(t.encode()).hexdigest()[:16]


def _versions(raw: str, names: dict, ctx: dict, used: set[str], tails: list[str]) -> list[str]:
    line = _fill(raw, names, ctx)
    if "{" in line:
        return []
    versions = [line]
    for tail in tails:
        extra = _fill(tail, names, ctx).strip()
        if extra and "{" not in extra:
            versions.append(f"{line.rstrip('.!?')}. {extra}")
    return [v for v in versions if fp(v) not in used]


def assemble(rng: random.Random, names: dict, ctx: dict, used: set[str], *,
             topic: str = "", adult: bool = False, with_cut: bool = False):
    pool = [s for s in SITUATIONS if adult or not s.get("adult")]
    if topic:
        same = [s for s in pool if s["topic"] == topic]
        if same:
            pool = same
    order = list(pool)
    rng.shuffle(order)
    for sit in order:
        steps = ("A", "B", "A2", "B2")
        n = min(len(sit[s]) for s in steps)
        indexes = list(range(n))
        rng.shuffle(indexes)
        for index in indexes:
            picked = {}
            ok = True
            for step in steps:
                tails = TAILS.get(sit["topic"], []) if step in ("A", "A2") else B_TAILS.get(sit["topic"], [])
                opts = _versions(sit[step][index], names, ctx, used, tails)
                if not opts:
                    ok = False
                    break
                picked[step] = rng.choice(opts)
            if not ok:
                continue
            lines = [("A", picked["A"]), ("B", picked["B"]), ("A", picked["A2"]), ("B", picked["B2"])]
            if with_cut and sit["cut"]:
                cut_raw = sit["cut"][index if index < len(sit["cut"]) else 0]
                cuts = _versions(cut_raw, names, ctx, used, [])
                if cuts:
                    lines.insert(2, ("C", rng.choice(cuts)))
            return sit["topic"], lines
    return None


def ambient_line(rng: random.Random, ctx: dict, used: set[str]) -> str | None:
    opts = []
    for raw in AMBIENT_LINES:
        line = _fill(raw, {}, ctx)
        if "{" in line or fp(line) in used:
            continue
        opts.append(line)
    if not opts:
        return None
    return rng.choice(opts)
